    `recharge_order_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '充值订单业务标识',
    `trade_order_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '关联交易订单业务标识，不建立外键',
    `user_id` VARCHAR(255) NOT NULL COMMENT '充值用户业务标识，兼容 users.user_id',
