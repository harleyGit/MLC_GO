    CONSTRAINT `ck_payment_recharge_order_coin_equation` CHECK (CAST(`total_coin` AS DECIMAL(30,0)) = CAST(`coin_amount` AS DECIMAL(30,0)) + CAST(`bonus_coin` AS DECIMAL(30,0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='充值订单事实，关联统一交易订单';

CREATE TABLE `payment_order` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '数据库内部自增主键',
    `payment_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '支付尝试业务标识，每次重复支付尝试可新建',
    `trade_order_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '关联交易订单业务标识，不建立外键',
    `user_id` VARCHAR(255) NOT NULL COMMENT '支付用户业务标识，兼容 users.user_id',
    `request_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '支付尝试请求幂等标识，与用户联合唯一；新尝试使用新请求标识',
    `request_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '规范化支付请求 SHA-256；重放必须比较哈希，不同内容返回冲突',
    `payment_type` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '支付方式，例如 COIN；本基础表不实现第三方 SDK',
    `currency` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '支付币种，支持 CNY 与 MLC_COIN；单个支付尝试不混用币种',
    `amount` BIGINT NOT NULL COMMENT '支付金额，整数最小单位，不得为负',
    `payment_status` TINYINT NOT NULL DEFAULT 0 COMMENT '支付状态：0INIT，1PENDING，2SUCCESS，3FAILED，4CLOSED',
    `client_type` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '发起支付的客户端类型，可为空',
    `merchant_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '外部商户业务标识，可为空',
    `channel` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '外部支付渠道标识，可为空',
    `external_payment_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '外部支付单号，可为空；同商户同渠道下唯一',
    `expire_at` DATETIME(3) NOT NULL COMMENT '支付尝试截止时间，UTC，精确到毫秒',
    `paid_at` DATETIME(3) DEFAULT NULL COMMENT '支付成功时间，UTC，精确到毫秒；未成功为空',
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC，精确到毫秒',
    `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，UTC，精确到毫秒',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_payment_order_payment_id` (`payment_id`),
    UNIQUE KEY `uk_payment_order_request_user` (`user_id`, `request_id`),
    UNIQUE KEY `uk_payment_order_external` (`merchant_id`, `channel`, `external_payment_id`),
    KEY `idx_payment_order_trade_id` (`trade_order_id`, `id`),
    KEY `idx_payment_order_user_created_id` (`user_id`, `created_at` DESC, `id` DESC),
    KEY `idx_payment_order_status_expire_id` (`payment_status`, `expire_at`, `id`),
    CONSTRAINT `ck_payment_order_amount_nonnegative` CHECK (`amount` >= 0),
    CONSTRAINT `ck_payment_order_external_scope` CHECK (`external_payment_id` IS NULL OR (`external_payment_id` <> '' AND `merchant_id` IS NOT NULL AND `merchant_id` <> '' AND `channel` IS NOT NULL AND `channel` <> ''))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='支付尝试事实，不代表已接入外部支付渠道';

