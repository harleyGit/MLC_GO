CREATE TABLE hg_error_code_catalog (
    code INT UNSIGNED NOT NULL PRIMARY KEY,
    error_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    module VARCHAR(32) CHARACTER SET ascii NOT NULL,
    submodule TINYINT UNSIGNED NOT NULL,
    http_status SMALLINT UNSIGNED NOT NULL,
    default_message VARCHAR(255) NOT NULL,
    retryable BOOLEAN NOT NULL DEFAULT FALSE,
    status ENUM('active','deprecated','reserved') NOT NULL DEFAULT 'active',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_error_key (error_key),
    KEY idx_module_status (module,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
