package main

import (
	"bytes"
	"os"
	"testing"
)

func TestHGPublishedCatalogMatchesGo(t *testing.T) {
	for format, path := range map[string]string{"json": "../../docs/error-codes.v1.json", "seed": "../../migrations/000090_error_code_catalog.up.sql"} {
		frozen, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		var generated bytes.Buffer
		if err = hgExport(&generated, format); err != nil {
			t.Fatal(err)
		}
		if format == "seed" {
			i := bytes.Index(frozen, []byte("INSERT INTO "))
			if i < 0 {
				t.Fatal("缺少目录初始数据")
			}
			frozen = frozen[i:]
		}
		if !bytes.Equal(generated.Bytes(), frozen) {
			t.Fatalf("%s 与发布基线不一致；新版本请显式审核协议和增量迁移", path)
		}
	}
}
